CREATE TABLE TB_TRAVESSIA_USUARIO (
    ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME VARCHAR2(100) NOT NULL,
    IDADE NUMBER(10,0) NOT NULL,
    PCD NUMBER(1,0) NOT NULL,
    PAPEL VARCHAR2(20) NOT NULL
);

CREATE TABLE TB_TRAVESSIA_SEMAFORO (
    ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DESCRICAO VARCHAR2(200) NOT NULL,
    LATITUDE FLOAT(53) NOT NULL,
    LONGITUDE FLOAT(53) NOT NULL,
    ATIVO NUMBER(1,0) DEFAULT 1 NOT NULL
);

CREATE TABLE TB_TRAVESSIA_SOLICITACAO (
    ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USUARIO_ID NUMBER(19,0) NOT NULL REFERENCES TB_TRAVESSIA_USUARIO(ID),
    SEMAFORO_ID NUMBER(19,0) NOT NULL REFERENCES TB_TRAVESSIA_SEMAFORO(ID),
    DATA_HORA_SOLICITACAO TIMESTAMP(6) NOT NULL,
    SEGUNDOS_EXTRAS NUMBER(10,0) NOT NULL,
    CONDICAO_CLIMATICA VARCHAR2(200)
);
